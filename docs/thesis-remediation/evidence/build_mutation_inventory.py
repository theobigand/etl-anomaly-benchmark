"""Regenerate docs/thesis-remediation/MUTATION_L4_INVENTORY.md from the policy, the 2026-11-07 campaign and the
focused records. Raw scores only; a focused record is marked stale when the module changed after its date.

    python docs/thesis-remediation/evidence/build_mutation_inventory.py
"""

import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
policy = json.loads((ROOT / "verification/mutation_risk_policy.json").read_text())["units"]
campaign = json.loads(
    (ROOT / "docs/thesis-remediation/evidence/risk-native-campaign-2026-11-07.json").read_text()
)["modules"]
focused = json.loads(
    (HERE := Path(__file__).parent / "mutation-focused-2026-11-12.json").read_text()
)["records"]


def changed_since(path, date):
    out = subprocess.run(
        ["git", "log", "--since", f"{date} 23:59", "--format=%h", "--", path],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.split()
    return out


changed = set(
    subprocess.run(
        ["git", "diff", "--name-only", "c8e3917", "HEAD"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.split()
)
rows = []
for path, unit in sorted(policy.items()):
    if unit["level"] != "L4":
        continue
    sha = hashlib.sha256((ROOT / path).read_bytes()).hexdigest()[:12]
    camp = campaign.get(path)
    foc = focused.get(path)
    row = {"path": path, "sha": sha, "reason": unit["reason"][:70]}
    row["campaign"] = f"{camp['killed']}/{camp['eligible']}" if camp else "absent"
    row["camp_status"] = (
        (camp["status"] + (" (source changed since)" if path in changed else ""))
        if camp
        else "no evidence"
    )
    if foc:
        pct = 100 * foc["killed"] / foc["total"]
        stale = changed_since(path, foc["date"]) if foc["date"] != "2026-11-12" else []
        row["focused"] = f"{foc['killed']}/{foc['total']} ({pct:.1f}%) {foc['date']}" + (
            " STALE" if stale else ""
        )
        row["status"] = ("stale focused; " if stale else "") + (
            "focused at or above 98 (not certified)" if pct >= 98 and not stale else "below 98"
        )
    elif camp:
        pct = 100 * camp["killed"] / camp["eligible"]
        row["focused"] = "-"
        row["status"] = (
            (
                "campaign PASS (historical, stale: source changed)"
                if path in changed
                else "campaign PASS (historical)"
            )
            if camp["status"] == "PASS"
            else (f"below 98 ({pct:.1f}%), {camp['status'].lower()}")
        )
    else:
        row["focused"] = "-"
        row["status"] = "no applicable evidence"
    rows.append(row)

lines = [
    "# L4 mutation inventory",
    "",
    "Generated by `docs/thesis-remediation/evidence/build_mutation_inventory.py` from the policy, the 2026-11-07",
    "native campaign (revision c8e3917) and `mutation-focused-2026-11-12.json`. Raw scores. Nothing here is a",
    "release certification: the campaign is historical and the focused runs are partial.",
    "",
    f"L4 modules: {len(rows)}. In the campaign: {sum(r['campaign'] != 'absent' for r in rows)}. "
    f"Absent from the campaign: {sum(r['campaign'] == 'absent' for r in rows)}. "
    f"With a focused record: {sum(r['focused'] != '-' for r in rows)}.",
    "",
    "| Module | Source sha | Campaign | Campaign status | Focused | Status |",
    "| --- | --- | --- | --- | --- | --- |",
]
for r in rows:
    lines.append(
        f"| `{r['path']}` | {r['sha']} | {r['campaign']} | {r['camp_status']} | {r['focused']} | {r['status']} |"
    )
(ROOT / "docs/thesis-remediation/MUTATION_L4_INVENTORY.md").write_text("\n".join(lines) + "\n")
print(len(rows), "rows")
