def line(path, m):
    extra = {k: v for k, v in m["counts"].items() if k not in ("killed", "survived")}
    short = f" ({', '.join(f'{k} {v}' for k, v in sorted(extra.items()))})" if extra else ""
    gap = m["needed_for_threshold"] - m["killed"]
    return f"| `{path}` | {m['level']} | {m['killed']}/{m['eligible']} | {m['raw_score']:.2f} | {m['threshold']} | {gap if gap > 0 else 0} | {m['counts'].get('survived', 0)}{short} |"


def table(status, key=None):
    rows = [(p, m) for p, m in modules.items() if m["status"] == status]
    rows.sort(
        key=key
        or (
            lambda r: (
                -r[1]["level"].count("L4"),
                r[1]["needed_for_threshold"] - r[1]["killed"],
                r[0],
            )
        )
    )
    head = "| Module | Level | Killed / eligible | Raw % | Required % | Killed still needed | Survivors (other outcomes) |\n| --- | --- | --- | --- | --- | --- | --- |\n"
    return head + "\n".join(line(p, m) for p, m in rows) + "\n"


